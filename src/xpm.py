"""Residual differential cross-phase modulation (Methods: cross-phase modulation).

The qubit error is generated by the DIFFERENTIAL H-V phase; any deterministic
mean phase is excluded and only the zero-mean fluctuating part enters.

Three implementations are provided:

  sigma2_closed      production path; exact for the flat-PSD model, O(n_channels)
  sigma2_spectral    direct frequency-domain quadrature   (reference)
  sigma2_covariance  position-domain double integral      (reference)

The two reference routes are independent of the closed form and of each other and
are used by the validation script.  `sigma2_spectral` cannot resolve the walk-off
oscillation for counter-propagation on any affordable grid; its usable range is
reported rather than silently assumed.
"""
import numpy as np
from scipy.special import exp1


def flat_psd(F, sigma_p2, band_hz):
    """Two-sided flat power-fluctuation PSD, W^2/Hz, with int S dF = sigma_p2."""
    F = np.asarray(F, dtype=float)
    return np.where(np.abs(F) <= band_hz, sigma_p2 / (2.0 * band_hz), 0.0)


def H_transfer(F, a_ci, d_walkoff, L_m):
    """H(F) = (1 - exp(-(a_ci + i 2 pi F d) L)) / (a_ci + i 2 pi F d),
    the Fourier transform of the launch-fluctuation propagator g(z) = exp(-a z)
    along tau(z) = d z, with the zero-denominator limit L."""
    x = a_ci + 1j * 2 * np.pi * np.asarray(F, dtype=float) * d_walkoff
    small = np.abs(x * L_m) < 1e-12
    safe = np.where(small, 1.0, x)
    return np.where(small, L_m + 0j, (1.0 - np.exp(-safe * L_m)) / safe)


def _overlap_integral(a, d, L, B):
    """I(a,d,L,B) = int_{-B}^{B} |H(F)|^2 dF / (2B).

    Equivalently  I = 2 int_0^L sinc(2 B d u) K(u) du  with
    K(u) = exp(-a u)(1 - exp(-2a(L-u)))/(2a), obtained by carrying out the F
    integral first.  Evaluated in closed form with the exponential integral:

        I = [G(a) - exp(-2aL) G(-a)] / (a beta),   beta = 2 pi B d
        G(s) = -( arg(s - i beta) + Im E_1((s - i beta) L) )

    Limits: d -> 0 gives L_eff^2; large beta L gives K(0)/(2 B d).
    """
    a = np.asarray(a, dtype=float)
    d = np.abs(np.asarray(d, dtype=float))
    beta = 2.0 * np.pi * B * d
    Leff2 = ((1.0 - np.exp(-a * L)) / a) ** 2
    tiny = beta * L < 1e-9
    b_safe = np.where(tiny, 1.0, beta)

    def G(s):
        w = s - 1j * b_safe
        return -(np.angle(w) + np.imag(exp1(w * L)))

    val = (G(a) - np.exp(-2.0 * a * L) * G(-a)) / (a * b_safe)
    return np.where(tiny, Leff2, val)


def sigma2_closed(dep, a_ci, d_walkoff, L_m, gamma_per_w_m, kappa,
                  rel_fluct, band_hz):
    """sigma_phi^2 = 4 sum_i gamma^2 kappa^2 int S_dP_i(F) |H_i(F)|^2 dF
    for the flat two-sided PSD S = sigma_p^2/(2B) on |F| <= B.

    Independent channels only (diagonal terms); correlated channels would add
    cross-spectral terms.
    """
    a_ci = np.broadcast_to(np.atleast_1d(np.asarray(a_ci, float)), (dep.n_channels,))
    d_walkoff = np.broadcast_to(np.atleast_1d(np.asarray(d_walkoff, float)),
                                (dep.n_channels,))
    sigma_p2 = (rel_fluct * dep.launch_w) ** 2
    I = _overlap_integral(a_ci, d_walkoff, L_m, band_hz)
    return float(4.0 * gamma_per_w_m ** 2 * kappa ** 2 * np.sum(sigma_p2 * I))


def resolution_requirement(d_walkoff, L_m, band_hz, points_per_cycle=60):
    """Grid size the direct frequency-domain quadrature would need in order to
    resolve cos(2 pi F d L) over |F| <= B."""
    cycles = band_hz * np.abs(np.asarray(d_walkoff, float)) * L_m
    return points_per_cycle * cycles + 1


def sigma2_spectral(dep, a_ci, d_walkoff, L_m, gamma_per_w_m, kappa,
                    rel_fluct, band_hz, n_F=2001):
    """Direct frequency-domain quadrature reference.  Returns (value, converged)
    where `converged` reports whether n_F resolved every channel's oscillation."""
    a_ci = np.broadcast_to(np.atleast_1d(np.asarray(a_ci, float)), (dep.n_channels,))
    d_walkoff = np.broadcast_to(np.atleast_1d(np.asarray(d_walkoff, float)),
                                (dep.n_channels,))
    need = resolution_requirement(d_walkoff, L_m, band_hz)
    F = np.linspace(-band_hz, band_hz, n_F)
    sigma_p2 = (rel_fluct * dep.launch_w) ** 2
    H = H_transfer(F[:, None], a_ci[None, :], d_walkoff[None, :], L_m)
    S = sigma_p2[None, :] / (2.0 * band_hz)
    val = np.trapezoid(S * np.abs(H) ** 2, F, axis=0)
    total = float(4.0 * gamma_per_w_m ** 2 * kappa ** 2 * np.sum(val))
    return total, bool(np.all(need <= n_F))


def sigma2_covariance(dep, a_ci, d_walkoff, L_m, gamma_per_w_m, kappa,
                      rel_fluct, band_hz, n_z=1201):
    """Position-domain double integral reference:

        sigma^2 = 4 sum_i gamma^2 kappa^2 int int g(z) g(z') R(tau(z)-tau(z')) dz dz'

    with R(tau) = sigma_p^2 sinc(2 B tau) for the flat PSD used above.
    """
    z = np.linspace(0.0, L_m, n_z)
    a_ci = np.broadcast_to(np.atleast_1d(np.asarray(a_ci, float)), (dep.n_channels,))
    d_walkoff = np.broadcast_to(np.atleast_1d(np.asarray(d_walkoff, float)),
                                (dep.n_channels,))
    total = 0.0
    for i in range(dep.n_channels):
        sigma_p2 = (rel_fluct * dep.launch_w[i]) ** 2
        g = np.exp(-a_ci[i] * z)
        dt = d_walkoff[i] * (z[:, None] - z[None, :])
        M = (g[:, None] * g[None, :]) * sigma_p2 * np.sinc(2.0 * band_hz * dt)
        inner = np.trapezoid(np.trapezoid(M, z, axis=1), z)
        total += 4.0 * gamma_per_w_m ** 2 * kappa ** 2 * inner
    return float(total)


def sigma2_legacy_capped(dep, a_ci, d_walkoff, L_m, gamma_per_w_m, kappa,
                         rel_fluct, band_hz):
    """The legacy capped-walk-off approximation, retained ONLY as an explicitly
    labelled approximation: L_eff replaced by min(L_eff, 1/(2 B |d|))."""
    a_ci = np.broadcast_to(np.atleast_1d(np.asarray(a_ci, float)), (dep.n_channels,))
    d_walkoff = np.broadcast_to(np.atleast_1d(np.asarray(d_walkoff, float)),
                                (dep.n_channels,))
    total = 0.0
    for i in range(dep.n_channels):
        sigma_p2 = (rel_fluct * dep.launch_w[i]) ** 2
        Leff = (1.0 - np.exp(-a_ci[i] * L_m)) / a_ci[i]
        cap = 1.0 / (2.0 * band_hz * max(d_walkoff[i], 1e-30))
        total += 4.0 * gamma_per_w_m ** 2 * kappa ** 2 * sigma_p2 * min(Leff, cap) * Leff
    return float(total)


def coherence_check(sigma2, n_samples=200000, seed=0):
    """Empirical <exp(i phi)> for a Gaussian phase sample versus exp(-sigma^2/2)."""
    rng = np.random.default_rng(seed)
    phi = rng.normal(0.0, np.sqrt(sigma2), n_samples)
    emp = float(np.abs(np.mean(np.exp(1j * phi))))
    return emp, float(np.exp(-0.5 * sigma2))
